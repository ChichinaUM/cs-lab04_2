public class main 
{
	public static void main (String[] args) 
	{
		System.out.println("Введите А и В \n");
		double A, B;
		A = 3; B = 5;
		System.out.println("А = " + A + "; В = " + B + " \n");
		System.out.println("Сумма А и В = " + (A + B) + "\n");
		System.out.println("Разность А и В = " + (A - B) + "\n");
		System.out.println("Произведение А и В = " + (A * B) + "\n");
		System.out.println("Частное А и В = " + (A / B) + "\n");
		System.out.println("Максимум А и В = " + 5 + "\n");
		System.out.println("Минимум А и В = " + 3 + "\n");
	}
}

